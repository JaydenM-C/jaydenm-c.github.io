#!/usr/bin/env python3
"""Slim the Font Awesome icon fonts down to the icons the site uses.

Font Awesome ships ~1,400 solid and ~500 brand icons (about 270 KB of font
files); the site uses a few dozen. This script:

  1. scans the site's templates, pages, posts, data, config, scripts and
     styles for icon names (fa-envelope, fa-github, ...) and raw icon codes
     (content: "\\f121" in Sass);
  2. writes _sass/vendor/font-awesome/_used-icons.scss, so the CSS only
     defines classes for those icons;
  3. cuts the full fonts in _sass/vendor/font-awesome/webfonts-full/ down to
     those icons and writes the result to assets/webfonts/;
  4. does the same for Academicons (ai-google-scholar, ai-orcid, ...): the
     full font is _sass/vendor/academicons-full/academicons.ttf, the result
     goes to assets/fonts/academicons.{woff2,ttf}.

Run it from the repository root whenever you use a new icon:

    python3 scripts/subset_icons.py

Needs: pip install fonttools brotli
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FA = ROOT / "_sass/vendor/font-awesome"
FULL = FA / "webfonts-full"
OUT = ROOT / "assets/webfonts"
FONTS = ["fa-solid-900", "fa-brands-400"]   # the two faces main.scss loads

SCAN = ["_includes", "_layouts", "_pages", "_posts", "_drafts", "_data",
        "_publications", "_config.yml", "index.html", "assets/js", "_sass"]
SKIP = {"main.min.js"}                       # built file; _main.js is scanned
# icons named at build time (e.g. "fa-{{ profile.network | downcase }}")
EXTRA = []


def icon_maps():
    """name -> codepoint for every icon, and the set of brand icon names."""
    text = (FA / "_variables.scss").read_text(encoding="utf8")
    codes = {m[1]: int(m[2], 16) for m in re.finditer(r"\$fa-var-([\w-]+):\s*\\([0-9a-f]+);", text)}
    def names(map_name):
        block = re.search(r"\$" + map_name + r":\s*\((.*?)\n\);", text, re.S).group(1)
        return set(re.findall(r'"([\w-]+)":', block))
    return codes, names("fa-icons"), names("fa-brand-icons")


ai_words = set()


def scan_sources():
    words, raw = set(), set()
    for entry in SCAN:
        p = ROOT / entry
        files = [p] if p.is_file() else [f for f in p.rglob("*") if f.is_file()] if p.exists() else []
        for f in files:
            if f.name in SKIP or "vendor/font-awesome" in f.as_posix():
                continue
            if f.suffix.lower() not in {".html", ".md", ".markdown", ".yml", ".yaml", ".json", ".js", ".scss", ".liquid"}:
                continue
            text = f.read_text(encoding="utf8", errors="ignore")
            words |= set(re.findall(r"\bfa-([a-z0-9-]+)", text))
            ai_words.update(re.findall(r"\bai-([a-z0-9-]+)", text))
            if f.suffix == ".scss":
                raw |= {int(c, 16) for c in re.findall(r'content:\s*["\']\\(f[0-9a-f]{3})["\']', text)}
    # profile icons on the CV page are built from the network names in cv.json
    cv = ROOT / "_data/cv.json"
    if cv.exists():
        for prof in json.loads(cv.read_text(encoding="utf8")).get("basics", {}).get("profiles", []):
            if prof.get("network"):
                words.add(prof["network"].lower())
    return words | set(EXTRA), raw


def main():
    codes, solid, brands = icon_maps()
    words, raw = scan_sources()
    used = sorted(w for w in words if w in solid or w in brands)
    unicodes = sorted({codes[n] for n in used if n in codes} | raw)
    if not used:
        sys.exit("no icons found - not touching anything")

    (FA / "_used-icons.scss").write_text(
        "// Generated by scripts/subset_icons.py - do not edit by hand.\n"
        "// The icons the site uses; Font Awesome's Sass only emits classes for\n"
        "// these (see _icons.scss and brands.scss).\n"
        "$fa-used-icons: (\n" + ",\n".join(f'  "{n}"' for n in used) + "\n);\n",
        encoding="utf8")

    uni = ",".join(f"U+{c:04X}" for c in unicodes)
    for font in FONTS:
        for flavor, ext in (("woff2", ".woff2"), (None, ".ttf")):
            cmd = [sys.executable, "-m", "fontTools.subset", str(FULL / f"{font}.ttf"),
                   f"--unicodes={uni}", f"--output-file={OUT / (font + ext)}",
                   "--layout-features=*", "--no-hinting", "--desubroutinize"]
            if flavor:
                cmd.append(f"--flavor={flavor}")
            subprocess.run(cmd, check=True)

    # Academicons
    css = (ROOT / "assets/css/academicons.css").read_text(encoding="utf8")
    ai_codes = {m[1]: int(m[2], 16) for m in re.finditer(r"\.ai-([\w-]+):before\s*\{\s*content:\s*\"\\([0-9a-f]+)\"", css)}
    ai_used = sorted(w for w in ai_words if w in ai_codes)
    ai_src = ROOT / "_sass/vendor/academicons-full/academicons.ttf"
    if ai_used:
        ai_uni = ",".join(f"U+{ai_codes[n]:04X}" for n in ai_used)
        for flavor, ext in (("woff2", ".woff2"), (None, ".ttf")):
            cmd = [sys.executable, "-m", "fontTools.subset", str(ai_src), f"--unicodes={ai_uni}",
                   f"--output-file={ROOT / 'assets/fonts' / ('academicons' + ext)}",
                   "--layout-features=*", "--no-hinting"]
            if flavor:
                cmd.append(f"--flavor={flavor}")
            subprocess.run(cmd, check=True)
        print(f"Academicons: {', '.join(ai_used)} -> "
              f"{(ROOT / 'assets/fonts/academicons.woff2').stat().st_size/1024:.0f} KB")

    before = sum((FULL / f"{f}.woff2").stat().st_size for f in FONTS)
    after = sum((OUT / f"{f}.woff2").stat().st_size for f in FONTS)
    print(f"{len(used)} icons ({len(unicodes)} glyphs): {', '.join(used)}")
    print(f"icon fonts (woff2): {before/1024:.0f} KB -> {after/1024:.0f} KB")


if __name__ == "__main__":
    main()
